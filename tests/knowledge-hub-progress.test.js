import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const file=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
test('Mapa: remove caixa interna com scroll duplo e preserva rolagem única no modal',()=>{
 const map=file('src/KnowledgeSiteMap.jsx'),css=file('src/styles.css')
 assert.match(map,/className="ops-modal ops-site-map-modal"/)
 assert.match(map,/className="ops-map-groups"/)
 assert.doesNotMatch(map,/maxHeight:'350px'|overflow:'auto',border:/)
 assert.match(css,/\.ops-site-map-modal \.ops-scroll\s*\{[^}]*min-height:0;max-height:none!important;overflow-y:auto/s)
 assert.match(css,/\.ops-map-groups\s*\{[^}]*max-height:none!important;overflow:visible!important/s)
})
test('Mapa: filtra, expande/recolhe seções, mostra seleção real',()=>{
 const map=file('src/KnowledgeSiteMap.jsx')
 assert.match(map,/setMapQuery/)
 assert.match(map,/setExpandedGroups/)
 assert.match(map,/Expandir todas as seções/)
 assert.match(map,/Recolher seções/)
 assert.match(map,/Nenhuma página corresponde à busca/)
 assert.match(map,/selected\.includes\(p\.url\)/)
 assert.match(map,/SELECT_LIMIT=12/)
 assert.match(map,/role="dialog"/)
})
test('Hub: contagem real para lote e progresso indefinido quando rede não informa bytes',()=>{
 const map=file('src/KnowledgeSiteMap.jsx')
 const progress=file('src/KnowledgeProgress.jsx')
 assert.match(map,/done:i\+1,total:chosen\.length/)
 assert.match(map,/done:processed,total:pending\.length/)
 assert.match(map,/Localizando páginas e sitemaps públicos/)
 assert.match(progress,/Number\.isFinite\(value\.total\)/)
 assert.match(progress,/role="progressbar"/)
 assert.match(progress,/aria-valuenow=\{measured\?done:undefined\}/)
 assert.match(progress,/indeterminate/)
 assert.doesNotMatch(progress,/setInterval|setTimeout|Math\.random/)
})
test('Hub: arquivo local tem progresso por bytes e PDF/DOCX faz etapa indeterminada',()=>{
 const ops=file('src/Operations.jsx')
 assert.match(ops,/reader\.onprogress=e=>/)
 assert.match(ops,/if\(e\.lengthComputable\)onProgress\(e\.loaded,e\.total\)/)
 assert.match(ops,/readKnowledgeBytes\(file/)
 assert.match(ops,/Extraindo texto de/)
 assert.match(ops,/setHubProgress\(\{label:'Documento cadastrado em revisão'/)
 assert.match(ops,/setHubProgress\(\{label:'Status salvo:/)
 assert.match(ops,/setHubProgress\(\{label:'Conteúdo do link pronto para revisão'/)
 assert.match(ops,/setHubProgress\(\{label:'Transcrição preparada para revisão'/)
})
test('Hub: aprovação permanece obrigatória, nenhuma gravação no mapeamento ou progresso',()=>{
 const map=file('src/KnowledgeSiteMap.jsx')
 const progress=file('src/KnowledgeProgress.jsx')
 assert.match(map,/window\.confirm/)
 assert.match(map,/result\.status!=='review'/)
 assert.doesNotMatch(progress,/fetch\(|create_document|publish_document/)
 assert.match(map,/Os agentes ainda não têm acesso/)
})
